from pathlib import Path
import pickle

import pandas as pd
import streamlit as st


# =========================
# 1. PAGE CONFIGURATION
# =========================

st.set_page_config(
    page_title="House Price Predictor",
    page_icon="🏠",
    layout="centered",
)


# =========================
# 2. LOAD MODEL
# =========================

MODEL_PATH = Path("models/model.pkl")

if not MODEL_PATH.exists():
    st.error(
        "The trained model was not found. "
        "Please run train.py first."
    )
    st.stop()

with open(MODEL_PATH, "rb") as file:
    model = pickle.load(file)


# =========================
# 3. HEADER
# =========================

st.title("House Price Predictor")

st.write(
    "Estimate a house's sale price using a "
    "Random Forest regression model."
)


# =========================
# 4. INPUTS
# =========================

st.subheader("Property Details")

col1, col2 = st.columns(2)

with col1:

    overall_qual = st.slider(
        "Overall Quality",
        min_value=1,
        max_value=10,
        value=5,
        help="Overall material and finish quality.",
    )

    gr_liv_area = st.number_input(
        "Living Area (sq ft)",
        min_value=300,
        max_value=10_000,
        value=1_500,
        step=50,
    )

    garage_cars = st.number_input(
        "Garage Capacity",
        min_value=0,
        max_value=5,
        value=2,
        step=1,
    )


with col2:

    total_bsmt_sf = st.number_input(
        "Basement Area (sq ft)",
        min_value=0,
        max_value=5_000,
        value=800,
        step=50,
    )

    full_bath = st.number_input(
        "Full Bathrooms",
        min_value=0,
        max_value=5,
        value=2,
        step=1,
    )

    year_built = st.number_input(
        "Year Built",
        min_value=1872,
        max_value=2025,
        value=2000,
        step=1,
    )


# =========================
# 5. CREATE INPUT DATA
# =========================

input_data = pd.DataFrame(
    [
        {
            "OverallQual": overall_qual,
            "GrLivArea": gr_liv_area,
            "GarageCars": garage_cars,
            "TotalBsmtSF": total_bsmt_sf,
            "FullBath": full_bath,
            "YearBuilt": year_built,
        }
    ]
)


# =========================
# 6. PREDICTION
# =========================

st.divider()

if st.button(
    "Predict House Price",
    use_container_width=True,
):

    prediction = model.predict(input_data)[0]

    st.success(
        f"Estimated Sale Price: ${prediction:,.0f}"
    )

    st.caption(
        "This estimate is generated by a "
        "Random Forest regression model trained "
        "on the Kaggle House Prices dataset."
    )


# =========================
# 7. DISCLAIMER
# =========================

st.divider()

st.caption(
    "This application is for educational and "
    "demonstration purposes only. Predictions "
    "are estimates and should not be considered "
    "professional real-estate valuations."
)